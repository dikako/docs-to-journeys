package appium

import (
	"fmt"
	"strconv"
	"strings"
)

// javaEmitter renders a JUnit-ready Java class: one By constant per element and
// a run(driver) method that replays the journey with explicit waits.
type javaEmitter struct{}

func (javaEmitter) FileName(s Script) string { return s.ClassName() + ".java" }

func (javaEmitter) Render(s Script) []byte {
	class := s.ClassName()
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("// Generated by docs-to-journeys from %s %s. Edit freely.\n", strings.ToLower(kindOf(s)), javaComment(strconv.Quote(s.Journey)))
	if s.FailedAt > 0 {
		w("// NOTE: the journey failed at step %d; steps after it were not recorded.\n", s.FailedAt)
	}
	w(`
import io.appium.java_client.AppiumBy;
import io.appium.java_client.android.AndroidDriver;
import org.openqa.selenium.By;
import org.openqa.selenium.WebElement;
import org.openqa.selenium.support.ui.ExpectedConditions;
import org.openqa.selenium.support.ui.WebDriverWait;

import java.time.Duration;

import static org.junit.jupiter.api.Assertions.assertTrue;

`)
	w("public final class %s {\n\n", class)

	for _, l := range s.Locators() {
		w("    public static final By %s = %s;\n", l.Name, javaBy(l))
	}
	if len(s.Locators()) > 0 {
		w("\n")
	}

	w("    /** Replays the %s %s. The app must already be launched. */\n", strings.ToLower(kindOf(s)), javaComment(s.Journey))
	w("    public static void run(AndroidDriver driver) {\n")
	w("        WebDriverWait wait = new WebDriverWait(driver, Duration.ofSeconds(10));\n")
	last := 0
	for _, st := range s.Steps {
		if st.Index != last { // one comment per journey action, even if it took several steps
			w("\n        // %d. %s\n", st.Index, javaComment(st.Text))
			last = st.Index
		}
		for _, line := range javaStep(st) {
			w("        %s\n", line)
		}
	}
	w("    }\n\n")
	w("    private static WebElement visible(WebDriverWait wait, By by) {\n")
	w("        return wait.until(ExpectedConditions.visibilityOfElementLocated(by));\n")
	w("    }\n\n")
	w("    private %s() {\n    }\n}\n", class)
	return []byte(b.String())
}

func javaBy(l Locator) string {
	return fmt.Sprintf("AppiumBy.%s(%s)", l.By, javaString(l.Value))
}

func javaStep(st Step) []string {
	el := func() string { return fmt.Sprintf("visible(wait, %s)", st.Locator.Name) }
	if st.Locator.IsZero() {
		switch st.Action {
		case Back:
			return []string{"driver.navigate().back();"}
		case Wait:
			return []string{"// wait: covered by the explicit waits on the next element"}
		default:
			return []string{fmt.Sprintf("// TODO: %s (no element recorded)", st.Action)}
		}
	}
	switch st.Action {
	case Tap:
		return []string{el() + ".click();"}
	case Type:
		return []string{
			el() + ".clear();",
			fmt.Sprintf("%s.sendKeys(%s);", el(), javaString(st.Input)),
		}
	case Verify:
		return []string{fmt.Sprintf("assertTrue(%s.isDisplayed(), %s);", el(), javaString(oneLine(st.Text)))}
	case Scroll:
		if sel := uiSelector(st.Locator); sel != "" {
			return []string{fmt.Sprintf("driver.findElement(AppiumBy.androidUIAutomator(%s));",
				javaString("new UiScrollable(new UiSelector().scrollable(true)).scrollIntoView("+sel+")"))}
		}
		return []string{"// TODO: scroll to " + st.Locator.Name}
	default:
		return []string{fmt.Sprintf("// TODO: %s on %s", st.Action, st.Locator.Name)}
	}
}

// uiSelector builds a UiSelector for scrolling an element into view.
func uiSelector(l Locator) string {
	switch l.By {
	case AccessibilityID:
		return "new UiSelector().description(" + javaString(l.Value) + ")"
	case ID:
		return "new UiSelector().resourceId(" + javaString(l.Value) + ")"
	case AndroidUIAutomator:
		return l.Value
	}
	return ""
}

func kindOf(s Script) string {
	if s.Kind == "" {
		return "Journey"
	}
	return s.Kind
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// javaString renders s as a Java string literal.
func javaString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04x`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// javaComment makes text safe inside // and /** */ comments.
func javaComment(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(oneLine(s), "*/", "* /"), `\u`, `\\u`)
}
